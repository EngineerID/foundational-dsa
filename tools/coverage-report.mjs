#!/usr/bin/env node
/**
 * Aggregate line coverage from Java (JaCoCo), Python (pytest-cov JSON), and Jest.
 * Writes coverage/summary.json and returns markdown for COVERAGE.md.
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'coverage');

function pct(covered, total) {
  if (total === 0) return 0;
  return Math.round((covered / total) * 1000) / 10;
}

function parseJacoco() {
  const xmlPath = path.join(ROOT, 'java', 'target', 'site', 'jacoco', 'jacoco.xml');
  if (!fs.existsSync(xmlPath)) return null;
  const text = fs.readFileSync(xmlPath, 'utf8');
  const counters = [...text.matchAll(/<counter type="LINE" missed="(\d+)" covered="(\d+)"/g)];
  if (!counters.length) return null;
  let missed = 0;
  let covered = 0;
  for (const m of counters) {
    missed += Number(m[1]);
    covered += Number(m[2]);
  }
  const total = missed + covered;
  return { language: 'java', covered, total, percent: pct(covered, total) };
}

function parsePythonJson() {
  const jsonPath = path.join(OUT_DIR, 'python-coverage.json');
  if (!fs.existsSync(jsonPath)) return null;
  const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  const totals = data.totals ?? data;
  const covered = totals.covered_lines ?? 0;
  const total = (totals.num_statements ?? totals.covered_lines + totals.missing_lines) || 0;
  const missed = totals.missing_lines ?? total - covered;
  const lineTotal = covered + missed;
  return { language: 'python', covered, total: lineTotal, percent: pct(covered, lineTotal) };
}

function parseJestSummary() {
  const candidates = [
    path.join(OUT_DIR, 'javascript-coverage-summary.json'),
    path.join(OUT_DIR, 'javascript', 'coverage-summary.json'),
  ];
  const jsonPath = candidates.find((p) => fs.existsSync(p));
  if (!jsonPath) return null;
  const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  const total = data.total;
  if (!total?.lines) return null;
  const covered = total.lines.covered ?? 0;
  const lineTotal = total.lines.total ?? 0;
  return { language: 'javascript', covered, total: lineTotal, percent: pct(covered, lineTotal) };
}

export function readCoverageSummary() {
  const languages = [parseJacoco(), parsePythonJson(), parseJestSummary()].filter(Boolean);
  if (!languages.length) return null;
  const covered = languages.reduce((n, l) => n + l.covered, 0);
  const total = languages.reduce((n, l) => n + l.total, 0);
  return {
    generatedAt: new Date().toISOString(),
    languages,
    overall: { covered, total, percent: pct(covered, total) },
  };
}

export function formatLineCoverageMarkdown(summary) {
  if (!summary) {
    return [
      '',
      '## Line coverage',
      '',
      '_Run `npm run coverage:report` after tests to populate line coverage totals._',
      '',
    ].join('\n');
  }
  const lines = [
    '',
    '## Line coverage',
    '',
    'Report-only aggregate (target ≥90% for this library). Regenerated by `npm run coverage:report`.',
    '',
    '| Language | Line % | Covered / total |',
    '|----------|-------:|----------------:|',
  ];
  for (const lang of summary.languages) {
    const label = lang.language.charAt(0).toUpperCase() + lang.language.slice(1);
    lines.push(`| ${label} | ${lang.percent}% | ${lang.covered} / ${lang.total} |`);
  }
  lines.push(
    `| **Overall** | **${summary.overall.percent}%** | **${summary.overall.covered} / ${summary.overall.total}** |`,
    '',
  );
  return lines.join('\n');
}

function pythonCmd() {
  for (const cmd of ['python3', 'python', 'py']) {
    try {
      execSync(`${cmd} --version`, { stdio: 'pipe', shell: true });
      return cmd;
    } catch {
      /* try next */
    }
  }
  return 'python3';
}

function collect() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const py = pythonCmd();
  execSync(`${py} -m pytest python -q --cov=dsa --cov-report=json:${path.join(OUT_DIR, 'python-coverage.json')}`, {
    cwd: ROOT,
    stdio: 'inherit',
    shell: true,
  });
  execSync(
    'npx jest --config javascript/jest.config.js --coverage --coverageReporters=json-summary --coverageDirectory=../coverage/javascript',
    { cwd: path.join(ROOT, 'javascript'), stdio: 'inherit', shell: true },
  );
  const jestSummarySrc = path.join(OUT_DIR, 'javascript', 'coverage-summary.json');
  const jestSummaryDst = path.join(OUT_DIR, 'javascript-coverage-summary.json');
  if (fs.existsSync(jestSummarySrc)) {
    fs.copyFileSync(jestSummarySrc, jestSummaryDst);
  }
  const jacocoXml = path.join(ROOT, 'java', 'target', 'site', 'jacoco', 'jacoco.xml');
  if (!fs.existsSync(jacocoXml)) {
    execSync('node tools/run-java-test.mjs', { cwd: ROOT, stdio: 'inherit' });
  }
}

function writeSummaryFile() {
  const summary = readCoverageSummary();
  if (!summary) return null;
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, 'summary.json'), JSON.stringify(summary, null, 2));
  return summary;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  if (process.argv.includes('--collect')) {
    collect();
  }
  const summary = writeSummaryFile();
  if (summary) {
    console.log(`Line coverage overall: ${summary.overall.percent}%`);
  } else if (process.argv.includes('--collect')) {
    console.error('Coverage collection finished but no summary could be parsed.');
    process.exit(1);
  } else {
    console.error('No coverage inputs found (run tests with coverage enabled first).');
    process.exit(1);
  }
}

export function getLineCoverageSummary() {
  const onDisk = path.join(OUT_DIR, 'summary.json');
  if (fs.existsSync(onDisk)) {
    return JSON.parse(fs.readFileSync(onDisk, 'utf8'));
  }
  return writeSummaryFile();
}

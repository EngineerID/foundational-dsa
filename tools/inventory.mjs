#!/usr/bin/env node
/**
 * Regenerates INVENTORY.md — topic index with source and test paths.
 * Usage: node tools/inventory.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { DOC_SPECS } from './doc-spec.mjs';
import { ITEMS } from './items.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'INVENTORY.md');

const JAVA_SPECIAL = {
  HashTableChaining: 'hashing/HashTableChaining',
  HashTableOpenAddressing: 'hashing/HashTableOpenAddressing',
  KruskalMST: 'graphs/KruskalMST',
  PrimMST: 'graphs/PrimMST',
  BoruvkaMST: 'graphs/BoruvkaMST',
  BST: 'trees/BST',
  BFS: 'graphs/BFS',
  DFS: 'graphs/DFS',
  AVLTree: 'trees/AVLTree',
  BTree: 'trees/BTree',
};

function javaMain(item) {
  const rel = JAVA_SPECIAL[item.java] ?? `${item.topic}/${item.java}`;
  return `java/src/main/java/com/dsa/examples/${rel}.java`;
}

function pyMain(item) {
  return `python/dsa/${item.topic}/${item.py}.py`;
}

function jsMain(item) {
  return `javascript/src/${item.topic}/${item.js}.js`;
}

function complexityLine(id) {
  const spec = DOC_SPECS[id];
  if (!spec?.complexity) return '—';
  return spec.complexity.replace(/\s+/g, ' ');
}

function render() {
  const lines = [
    '# Inventory',
    '',
    'Generated by `npm run inventory`. Do not edit by hand.',
    '',
    '| # | Topic | Area | Complexity (doc-spec) | Java | Python | JavaScript |',
    '|---|-------|------|------------------------|------|--------|------------|',
  ];
  ITEMS.forEach((item, i) => {
    lines.push(
      `| ${i + 1} | ${item.id} | ${item.topic} | ${complexityLine(item.id)} | \`${javaMain(item)}\` | \`${pyMain(item)}\` | \`${jsMain(item)}\` |`,
    );
  });
  lines.push('', `**Topics:** ${ITEMS.length}`, '');
  return `${lines.join('\n')}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const next = render();
  if (check) {
    if (!fs.existsSync(OUT)) {
      console.error('INVENTORY.md is missing; run npm run inventory');
      process.exit(1);
    }
    const current = fs.readFileSync(OUT, 'utf8');
    if (current !== next) {
      console.error('INVENTORY.md is stale; run npm run inventory');
      process.exit(1);
    }
    console.log('INVENTORY.md is up to date.');
    return;
  }
  fs.writeFileSync(OUT, next);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

main();

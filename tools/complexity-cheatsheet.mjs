#!/usr/bin/env node
/**
 * Regenerates docs/complexity-cheatsheet.md from tools/doc-spec.mjs.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { DOC_SPECS } from './doc-spec.mjs';
import { ITEMS } from './items.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs', 'complexity-cheatsheet.md');

function parseTimeSpace(complexity) {
  const time = complexity.match(/Time O\([^)]+\)/i)?.[0] ?? '—';
  const space = complexity.match(/Space O\([^)]+\)/i)?.[0] ?? '—';
  return { time, space };
}

export function renderComplexityCheatsheet() {
  const byTopic = new Map();
  for (const item of ITEMS) {
    if (!byTopic.has(item.topic)) byTopic.set(item.topic, []);
    byTopic.get(item.topic).push(item);
  }
  const lines = [
    '# Complexity cheat sheet',
    '',
    'Generated by `npm run complexity:cheatsheet`. Do not edit by hand.',
    '',
    'Primary operations from [`tools/doc-spec.mjs`](../tools/doc-spec.mjs). See also [README complexity table](../README.md#complexity-primary-operations) and per-topic [docs/items/](items/).',
    '',
  ];
  for (const topic of [...byTopic.keys()].sort()) {
    lines.push(`## ${topic}`, '', '| Topic id | Time | Space | doc-spec |', '|----------|------|-------|----------|');
    for (const item of byTopic.get(topic).sort((a, b) => a.id.localeCompare(b.id))) {
      const spec = DOC_SPECS[item.id];
      const raw = spec?.complexity?.replace(/\s+/g, ' ') ?? '—';
      const { time, space } = spec?.complexity ? parseTimeSpace(raw) : { time: '—', space: '—' };
      lines.push(`| \`${item.id}\` | ${time} | ${space} | ${raw} |`);
    }
    lines.push('');
  }
  lines.push(`**Topics:** ${ITEMS.length}`, '');
  return `${lines.join('\n')}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const next = renderComplexityCheatsheet();
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== next) {
      console.error('docs/complexity-cheatsheet.md is out of date (run npm run complexity:cheatsheet)');
      process.exit(1);
    }
    console.log('Complexity cheat sheet is up to date.');
    return;
  }
  fs.writeFileSync(OUT, next);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

main();
